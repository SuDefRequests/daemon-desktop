import type { InferenceProvider } from "./types";
import { artifactFilename } from "./filenames";
// Deliberate, bounded mock latency; no animation adds inference delays.
export const MOCK_GENERATION_MS = 1000;
export const mockProvider: InferenceProvider = {
  mode: "mock",
  async generate({ prompt, task }) {
    await new Promise((resolve) => setTimeout(resolve, MOCK_GENERATION_MS));
    const kind =
      task === "chat"
        ? /\b(code|python|script)\b/i.test(prompt)
          ? "code"
          : /\b(sheet|csv|spreadsheet)\b/i.test(prompt)
            ? "spreadsheet"
            : /\b(presentation|slides)\b/i.test(prompt)
              ? "presentation"
              : /\b(document|draft|notes)\b/i.test(prompt)
                ? "document"
                : "chat"
        : task;
    const title = prompt.replace(/[\r\n]/g, " ").slice(0, 180);
    if (kind === "chat")
      return {
        reply: `This is a mock response to “${title}”.\n\nYour device is disconnected, so Qwen has not processed this request. Choose a productivity card to create a sample file, or use a quick tool to prepare your next prompt.`,
      };
    const samples = {
      code: {
        content:
          '# VIDUR AI mock example — review before use.\n# This fixed example is not inferred from your prompt.\ndef calculate_total(values):\n    return sum(values)\n\nif __name__ == "__main__":\n    print(calculate_total([10, 20, 30]))\n',
      },
      document: {
        content: `# Draft document\n\nRequested brief: ${title}\n\n## Overview\nThis is a sample document created by VIDUR AI in mock mode.\n\n## Next steps\n- Clarify the objective and audience.\n- Gather supporting information.\n- Review and refine the draft.\n`,
      },
      presentation: {
        content: `# Presentation outline\n\nBrief: ${title}\n\n## Slide 1 — Introduction\nIntroduce the topic and the purpose.\n\n## Slide 2 — Key ideas\nDescribe three key points with examples.\n\n## Slide 3 — Next steps\nSummarize and suggest a next action.\n\nMock outline; this is a Markdown file, not a PowerPoint deck.\n`,
      },
      spreadsheet: {
        content:
          "Item,Category,Quantity,Unit price,Total\nNotebook,Stationery,3,5,15\nPen,Stationery,10,2,20\nFolder,Stationery,4,3,12\n",
      },
    };
    return {
      reply:
        "Your sample file is ready. This fixed mock example demonstrates the file workflow; it was not generated by Qwen. You can preview it below or find it in My files.",
      file: { ...samples[kind], name: artifactFilename(prompt, kind), kind },
    };
  },
};
